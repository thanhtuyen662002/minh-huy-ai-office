import { isCanonicalCompanyId } from "./company-scope";

export const requestStatuses = {
  new: "Mới", needs_clarification: "Cần hỏi lại", in_progress: "Đang xử lý", done: "Xong", rejected: "Từ chối",
} as const;
export type RequestStatus = keyof typeof requestStatuses;
export type CustomerRequest = {
  code: string; id: string; status: RequestStatus; origin: "ai_extracted"; customerName: string; summary: string;
  sourceGroupExternalId: string; sourceGroupName: string; assigneeUserId: string | null;
  createdAt: string; updatedAt: string; rowVersion: string;
};
export type CustomerRequestPage = { items: CustomerRequest[]; offset: number; limit: number; hasMore: boolean };
export type CustomerRequestEvent = { eventType: "created" | "status_changed" | "assignee_changed";
  actorType: "service" | "user" | "zalo_member"; actorId: string; actorName: string | null; oldValue: string | null; newValue: string | null; timestamp: string };
export type CustomerRequestDetail = {
  request: CustomerRequest; reportedBy: string; customerDesiredDueText: string | null; sourceWindowFrom: string; sourceWindowTo: string;
  items: { content: string; priority: "high" | "medium" | "low"; kind: "bug" | "feature" | "question" | "data" }[];
  evidence: { quote: string; sourceMessageId: string; senderName: string; messageTimestamp: string }[];
  openQuestions: string[]; events: CustomerRequestEvent[];
};
export type CustomerRequestPatch = { rowVersion: string; status?: RequestStatus; assigneeUserId?: string | null };
export const requestConflict = "Phiếu vừa được người khác cập nhật, tải lại để xem bản mới";

const object = (value: unknown): value is Record<string, unknown> => !!value && typeof value === "object" && !Array.isArray(value);
const text = (value: unknown, maximum: number): value is string => typeof value === "string" && value.trim().length > 0
  && value.length <= maximum && !value.includes("\0") && !/[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/u.test(value);
const date = (value: unknown): value is string => typeof value === "string" && value.length <= 40 && Number.isFinite(Date.parse(value));
export const isRequestStatus = (value: unknown): value is RequestStatus => typeof value === "string" && Object.hasOwn(requestStatuses, value);
// Codes are generated by the bridge as YC- plus a counter padded to at least four digits.
export const isRequestCode = (value: unknown): value is string => typeof value === "string" && /^YC-[0-9]{4,21}$/.test(value);
const version = (value: unknown): value is string => typeof value === "string" && /^[A-Za-z0-9+/]{10}[AEIMQUYcgkosw048]=$/.test(value);

export function parseCustomerRequest(value: unknown, code?: string): CustomerRequest | null {
  if (!object(value) || !isRequestCode(value.code) || code !== undefined && value.code !== code || !isCanonicalCompanyId(value.id)
    || !isRequestStatus(value.status) || value.origin !== "ai_extracted" || !text(value.customerName, 200) || !text(value.summary, 8000)
    || !text(value.sourceGroupExternalId, 200) || !text(value.sourceGroupName, 200)
    || value.assigneeUserId !== null && !isCanonicalCompanyId(value.assigneeUserId)
    || !date(value.createdAt) || !date(value.updatedAt) || !version(value.rowVersion)) return null;
  return { code: value.code, id: value.id, status: value.status, origin: value.origin, customerName: value.customerName,
    summary: value.summary, sourceGroupExternalId: value.sourceGroupExternalId, sourceGroupName: value.sourceGroupName,
    assigneeUserId: value.assigneeUserId, createdAt: value.createdAt, updatedAt: value.updatedAt, rowVersion: value.rowVersion };
}

export function parseCustomerRequestPage(value: unknown, offset: number, limit: number): CustomerRequestPage | null {
  if (!object(value) || value.offset !== offset || value.limit !== limit || typeof value.hasMore !== "boolean"
    || !Array.isArray(value.items) || value.items.length > limit || value.hasMore && value.items.length !== limit) return null;
  const items: CustomerRequest[] = [];
  for (const raw of value.items) {
    const item = parseCustomerRequest(raw);
    if (!item || items.some(old => old.id === item.id || old.code === item.code)
      || items.length > 0 && Date.parse(items[items.length - 1].createdAt) < Date.parse(item.createdAt)) return null;
    items.push(item);
  }
  return { items, offset, limit, hasMore: value.hasMore };
}

export function parseCustomerRequestDetail(value: unknown, code: string): CustomerRequestDetail | null {
  if (!object(value)) return null;
  const request = parseCustomerRequest(value.request, code);
  if (!request || !text(value.reportedBy, 200) || value.customerDesiredDueText !== null && !text(value.customerDesiredDueText, 1000)
    || !date(value.sourceWindowFrom) || !date(value.sourceWindowTo) || Date.parse(value.sourceWindowFrom) > Date.parse(value.sourceWindowTo)
    || !Array.isArray(value.items) || value.items.length < 1 || value.items.length > 50
    || !Array.isArray(value.evidence) || value.evidence.length > 100 || !Array.isArray(value.openQuestions) || value.openQuestions.length > 50
    || !value.openQuestions.every(item => text(item, 1000)) || !Array.isArray(value.events)) return null;
  const items: CustomerRequestDetail["items"] = [], evidence: CustomerRequestDetail["evidence"] = [], events: CustomerRequestEvent[] = [];
  for (const item of value.items) {
    if (!object(item) || !text(item.content, 4000) || !["high", "medium", "low"].includes(String(item.priority))
      || !["bug", "feature", "question", "data"].includes(String(item.kind))) return null;
    items.push({ content: item.content, priority: item.priority as typeof items[number]["priority"], kind: item.kind as typeof items[number]["kind"] });
  }
  for (const item of value.evidence) {
    if (!object(item) || !text(item.quote, 2000) || !text(item.sourceMessageId, 200) || !text(item.senderName, 200) || !date(item.messageTimestamp)) return null;
    evidence.push({ quote: item.quote, sourceMessageId: item.sourceMessageId, senderName: item.senderName, messageTimestamp: item.messageTimestamp });
  }
  for (const item of value.events) {
    if (!object(item) || !["created", "status_changed", "assignee_changed"].includes(String(item.eventType))
      || !["service", "user", "zalo_member"].includes(String(item.actorType)) || !isCanonicalCompanyId(item.actorId)
      || item.actorName !== undefined && item.actorName !== null && !text(item.actorName, 200) || item.actorType === "zalo_member" && !text(item.actorName, 200)
      || item.oldValue !== null && !text(item.oldValue, 200) || item.newValue !== null && !text(item.newValue, 200) || !date(item.timestamp)) return null;
    events.push({ eventType: item.eventType as CustomerRequestEvent["eventType"], actorType: item.actorType as CustomerRequestEvent["actorType"],
      actorId: item.actorId, actorName: typeof item.actorName === "string" ? item.actorName : null, oldValue: item.oldValue, newValue: item.newValue, timestamp: item.timestamp });
  }
  return { request, reportedBy: value.reportedBy, customerDesiredDueText: value.customerDesiredDueText, sourceWindowFrom: value.sourceWindowFrom,
    sourceWindowTo: value.sourceWindowTo, items, evidence, openQuestions: value.openQuestions, events };
}

export function isCustomerRequestPatch(value: unknown): value is CustomerRequestPatch {
  return object(value) && Object.keys(value).every(key => ["rowVersion", "status", "assigneeUserId"].includes(key)) && version(value.rowVersion)
    && (Object.hasOwn(value, "status") || Object.hasOwn(value, "assigneeUserId"))
    && (!Object.hasOwn(value, "status") || isRequestStatus(value.status))
    && (!Object.hasOwn(value, "assigneeUserId") || value.assigneeUserId === null || isCanonicalCompanyId(value.assigneeUserId));
}
